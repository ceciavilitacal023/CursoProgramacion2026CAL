
# Ejercicio 4: Conjuntos

frutas1 = {"manzana", "pera", "uva", "mango"}

frutas2 = {"pera", "uva", "sandia", "naranja"}

# Unión
print("Unión:", frutas1 | frutas2)

# Intersección
print("Intersección:", frutas1 & frutas2)

# Diferencia
print("Diferencia:", frutas1 - frutas2)

# Diferencia simétrica
print("Diferencia simétrica:", frutas1 ^ frutas2)